/*
 * Additional source-backed connectors for the beta reading graph.
 *
 * These are deliberately structural: the reader sees a named historical
 * relationship and its attribution, never the source's rank, fortune or
 * character predicate as a claim about them. The full source text remains in
 * the registry for auditability. Connector depth is increased by adding
 * independently witnessed relationships, not by synthesising pairwise edges.
 */

const connectorRecord = (fields) => ({
  sourceText: null,
  sectionLocator: null,
  sectionLocatorStatus: "NOT_RECORDED",
  folioLocator: null,
  folioLocatorStatus: "NOT_RECORDED",
  historicalStates: [],
  relationshipPredicate: null,
  historicalPredicateCategories: [],
  sourceRuleGroupId: null,
  disagreementIds: [],
  alternateConnectorIds: [],
  supportingSourceIds: [],
  note: null,
  ...fields,
});

const construct = (id) => ({
  participantId: id,
  nodeType: "CONSTRUCT",
  constructId: id,
  lineageId: null,
  constituentId: null,
  conceptId: null,
  relatedSystemId: null,
  memberScope: "ALL_MEMBERS",
});

const constituent = (id, constructId) => ({
  participantId: id,
  nodeType: "CONSTITUENT",
  constructId,
  lineageId: null,
  constituentId: id,
  conceptId: null,
  relatedSystemId: null,
  memberScope: "NODE",
});

const sourceBacked = ({
  connectorId,
  constructId,
  targetId,
  sourceId,
  sourceText,
  sectionLocator,
  folioLocator,
  measurementAvailability,
  textualLayer = "BASE_TEXT",
  disagreementIds = [],
  note,
  evidenceStrength = "VERIFIED_PRIMARY",
}) => connectorRecord({
  connectorId,
  relationshipType: "CORRESPONDS_TO",
  relationshipDirection: { kind: "UNDIRECTED" },
  graphScope: "CORE_HERITAGE",
  participants: [construct(constructId), constituent(targetId, constructId)],
  evidenceClass: "EXPLICITLY_ATTESTED",
  evidenceStrength,
  sourceId,
  textualLayer,
  sourceText,
  sourceTextStatus: "VERIFIED",
  sectionLocator,
  sectionLocatorStatus: "VERIFIED",
  folioLocator,
  folioLocatorStatus: "VERIFIED",
  folioLocatorKind: "WYG_PB",
  measurementAvailability,
  runtimePolicy: "HERITAGE_PRESENTATION_ALLOWED",
  prohibitedForUserInference: true,
  disagreementIds,
  note,
});

